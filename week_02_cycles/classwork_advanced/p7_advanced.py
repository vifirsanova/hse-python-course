# ------------------------------------------------------------
# Задача 4.8 (уровень 3). Допишите строку
# ------------------------------------------------------------
# Найдите максимальный элемент матрицы:
# matrix = [[1, 5], [3, 4]]
# mx = matrix[0][0]
# for row in matrix:
#     for x in row:
#         ???

def task_4_8(matrix):
    mx = matrix[0][0]
    for row in matrix:
        for x in row:
            if x > mx:
                mx = x
    return mx


# ------------------------------------------------------------
# Задача 4.9 (уровень 3). Напишите сами
# ------------------------------------------------------------
# Запросите число n и выведите таблицу умножения
# от 1 до n в виде вложенного списка.

def task_4_9(n):
    return [[i * j for j in range(1, n + 1)]
            for i in range(1, n + 1)]


